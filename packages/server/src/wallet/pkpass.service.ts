import { createHash } from 'node:crypto';

/**
 * Builds and signs `.pkpass` bundles (PASS-A-11).
 *
 * A `.pkpass` is a ZIP of `pass.json`, its assets, a `manifest.json` mapping every file to its
 * SHA-1, and a detached PKCS#7 `signature` over that manifest.
 *
 * The manifest half is implemented here in full and is exactly testable. The **signature** is not:
 * it needs the issuer's Pass Type ID certificate and Apple's WWDR intermediate, and Node has no
 * PKCS#7 detached signing primitive. Rather than pretend, signing goes behind [PkPassSigner] —
 * an OpenSSL-backed implementation is the usual answer, and a host may substitute an HSM.
 *
 * PassKit verifies the signature when the pass is added, so an unsigned or wrongly-signed bundle
 * fails on device rather than silently "working".
 */

export interface PkPassFile {
  /** Path within the bundle, e.g. "pass.json", "icon.png", "en.lproj/pass.strings". */
  name: string;
  contents: Buffer;
}

/** Produces a detached PKCS#7 (DER) signature over the manifest bytes. */
export interface PkPassSigner {
  sign(manifest: Buffer): Promise<Buffer>;
}

export class PkPassBuildError extends Error {}

export class PkPassBuilder {
  /** Files Apple requires in every pass bundle. */
  static readonly REQUIRED_FILES = ['pass.json', 'icon.png'] as const;

  /** Names the builder generates; an issuer supplying them would be overwritten silently. */
  static readonly RESERVED_FILES = ['manifest.json', 'signature'] as const;

  constructor(private readonly signer: PkPassSigner) {}

  /**
   * `manifest.json` maps each bundle file to the **SHA-1** of its bytes.
   *
   * SHA-1 is not a choice: PassKit defines the manifest that way, and a SHA-256 manifest produces
   * a bundle Wallet rejects. It is an integrity index over already-signed content, not a security
   * primitive on its own — the PKCS#7 signature over this manifest is what carries the trust.
   */
  static buildManifest(files: PkPassFile[]): Buffer {
    const manifest: Record<string, string> = {};
    for (const file of files) {
      manifest[file.name] = createHash('sha1').update(file.contents).digest('hex');
    }
    // Stable key order so the same inputs always produce byte-identical manifests, which makes
    // the signature reproducible and the tests meaningful.
    const ordered = Object.fromEntries(Object.entries(manifest).sort(([a], [b]) => a.localeCompare(b)));
    return Buffer.from(JSON.stringify(ordered), 'utf8');
  }

  static validate(files: PkPassFile[]): void {
    if (files.length === 0) throw new PkPassBuildError('A pkpass bundle needs at least pass.json and icon.png');

    const names = new Set(files.map((f) => f.name));
    for (const required of PkPassBuilder.REQUIRED_FILES) {
      if (!names.has(required)) {
        throw new PkPassBuildError(`pkpass bundle is missing required file '${required}'`);
      }
    }
    for (const reserved of PkPassBuilder.RESERVED_FILES) {
      if (names.has(reserved)) {
        throw new PkPassBuildError(
          `'${reserved}' is generated by the builder and must not be supplied`
        );
      }
    }
    if (names.size !== files.length) {
      throw new PkPassBuildError('pkpass bundle contains duplicate file names');
    }

    const passJson = files.find((f) => f.name === 'pass.json')!;
    let parsed: Record<string, unknown>;
    try {
      parsed = JSON.parse(passJson.contents.toString('utf8'));
    } catch {
      throw new PkPassBuildError('pass.json is not valid JSON');
    }
    for (const field of ['passTypeIdentifier', 'serialNumber', 'teamIdentifier', 'organizationName', 'description']) {
      if (typeof parsed[field] !== 'string' || !(parsed[field] as string)) {
        throw new PkPassBuildError(`pass.json is missing required field '${field}'`);
      }
    }
    if (typeof parsed.formatVersion !== 'number') {
      throw new PkPassBuildError("pass.json is missing numeric 'formatVersion'");
    }
  }

  /**
   * Validates, hashes and signs, returning every file the ZIP must contain.
   *
   * Zipping itself is left to the caller: the repo has no archiver dependency, and adding one to
   * write a store-only ZIP would be more surface than value. The returned list is exactly the
   * bundle contents, in the order Apple expects.
   */
  async build(files: PkPassFile[]): Promise<PkPassFile[]> {
    PkPassBuilder.validate(files);
    const manifest = PkPassBuilder.buildManifest(files);
    const signature = await this.signer.sign(manifest);
    if (!signature || signature.length === 0) {
      throw new PkPassBuildError('The signer returned an empty signature; refusing to emit an unsigned pass');
    }
    return [
      ...files,
      { name: 'manifest.json', contents: manifest },
      { name: 'signature', contents: signature },
    ];
  }

  /** The `passTypeIdentifier:serialNumber` id the client tracks this pass by. */
  static passIdFrom(passJson: Buffer): string {
    const parsed = JSON.parse(passJson.toString('utf8'));
    return `${parsed.passTypeIdentifier}:${parsed.serialNumber}`;
  }
}

/**
 * Fails closed. Wiring a real signer is the host's job, and doing nothing is safer than emitting
 * a bundle PassKit will reject on device with a message the user cannot act on.
 */
export class UnconfiguredPkPassSigner implements PkPassSigner {
  async sign(): Promise<Buffer> {
    throw new PkPassBuildError(
      'No pkpass signer is configured. Supply a PkPassSigner backed by `openssl smime -sign -binary ' +
        '-signer <passTypeId.pem> -certfile <AppleWWDRCA.pem> -outform DER`, or an HSM.'
    );
  }
}
