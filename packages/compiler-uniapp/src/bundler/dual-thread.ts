/**
 * @goat/compiler-uniapp Dual-Thread Bundler
 * Compiles Uni-app project into isolated logic thread (appservice.worker.js) + view thread (webview.html + appview.renderer.js).
 */
import { generateIntegrityManifest } from './integrity.js';
import { transformRpxInCss } from '../runtime/rpx.js';
import type {
  BundleFileArtifact,
  BundlerInput,
  BundlerOutput,
} from '../types.js';

export function compileDualThreadBundle(input: BundlerInput): BundlerOutput {
  const artifacts: BundleFileArtifact[] = [];

  // 1. Emit manifest.json
  const manifestJson = JSON.stringify(input.manifest, null, 2);
  artifacts.push({
    path: 'manifest.json',
    content: manifestJson,
  });

  // 2. Emit goat.config.json
  const goatConfigJson = JSON.stringify(input.goatConfig, null, 2);
  artifacts.push({
    path: 'goat.config.json',
    content: goatConfigJson,
  });

  // 3. Emit appservice.worker.js (Logic thread sandbox)
  const workerLogicCode = generateWorkerScript(input);
  artifacts.push({
    path: 'appservice.worker.js',
    content: workerLogicCode,
  });

  // 4. Emit webview.html (View thread container)
  const webviewHtml = generateWebviewHtml(input);
  artifacts.push({
    path: 'webview.html',
    content: webviewHtml,
  });

  // 5. Emit appview.renderer.js (View thread DOM renderer)
  const rendererCode = generateRendererScript(input);
  artifacts.push({
    path: 'appview.renderer.js',
    content: rendererCode,
  });

  // 6. Emit appview.css (Global styles with rpx transformed)
  const baseCss = `
/* Goat Mini-App Viewport Baseline */
html, body {
  margin: 0;
  padding: 0;
  width: 100%;
  height: 100%;
  box-sizing: border-box;
  -webkit-tap-highlight-color: transparent;
  font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif;
  background-color: ${input.manifest.window?.backgroundColor || '#F8F8F8'};
}

*, *::before, *::after {
  box-sizing: inherit;
}

.goat-page-container {
  min-height: 100%;
  display: flex;
  flex-direction: column;
}
`;
  const transformedCss = transformRpxInCss(baseCss);
  artifacts.push({
    path: 'appview.css',
    content: transformedCss,
  });

  // 7. Emit Subpackage chunks if defined
  if (input.goatConfig.subpackages && input.goatConfig.subpackages.length > 0) {
    for (const sub of input.goatConfig.subpackages) {
      const subWorkerPath = `${sub.root}/${sub.name || 'subpackage'}.worker.js`;
      const subViewPath = `${sub.root}/${sub.name || 'subpackage'}.view.js`;

      const subWorkerContent = `
// Subpackage Logic Chunk: ${sub.root}
(function(global) {
  'use strict';
  global.__GOAT_REGISTER_SUBPACKAGE__?.('${sub.root}', {
    name: '${sub.name || sub.root}',
    pages: ${JSON.stringify(sub.pages)},
    loadedAt: Date.now()
  });
})(typeof globalThis !== 'undefined' ? globalThis : self);
`;

      const subViewContent = `
// Subpackage View Chunk: ${sub.root}
(function(global) {
  'use strict';
  global.__GOAT_REGISTER_SUBPACKAGE_VIEW__?.('${sub.root}', {
    pages: ${JSON.stringify(sub.pages)}
  });
})(typeof window !== 'undefined' ? window : this);
`;

      artifacts.push({ path: subWorkerPath, content: subWorkerContent.trim() });
      artifacts.push({ path: subViewPath, content: subViewContent.trim() });
    }
  }

  // 8. Generate SHA-256 integrity manifest
  const integrity = generateIntegrityManifest(artifacts);
  artifacts.push({
    path: 'integrity.json',
    content: JSON.stringify(integrity, null, 2),
  });

  return {
    artifacts,
    integrity,
    entryPage: input.manifest.entryPage,
    threadModel: 'dual-thread',
  };
}

function generateWorkerScript(input: BundlerInput): string {
  return `/**
 * Goat WebView Mini-App Logic Thread
 * AppID: ${input.manifest.appId} | Version: ${input.manifest.version}
 * Auto-generated by @goat/compiler-uniapp
 */
(function(global) {
  'use strict';

  // 1. Initial State & Runtime Registry
  const __GOAT_APP_ID__ = ${JSON.stringify(input.manifest.appId)};
  const __GOAT_ENTRY_PAGE__ = ${JSON.stringify(input.manifest.entryPage)};
  const __GOAT_PAGES__ = ${JSON.stringify(input.goatConfig.pages)};
  const __GOAT_PAGE_STYLES__ = ${JSON.stringify(input.goatConfig.pageStyles)};
  const __GOAT_SUBPACKAGES__ = ${JSON.stringify(input.goatConfig.subpackages || [])};

  // 2. Global Bridge Injection
  const uni = (typeof global.uni !== 'undefined') ? global.uni : {};
  global.uni = uni;

  // 3. Mini-App Lifecycle Management
  const appInstance = {
    onLaunch: function(options) {
      console.log('[GoatWorker] App launched:', __GOAT_APP_ID__, options);
    },
    onShow: function(options) {
      console.log('[GoatWorker] App shown');
    },
    onHide: function() {
      console.log('[GoatWorker] App hidden');
    }
  };

  // 4. Message Loop with Host WebView / JSBridge
  global.onmessage = function(event) {
    const message = event.data;
    if (!message || typeof message !== 'object') return;

    switch (message.type) {
      case 'INIT_APP':
        appInstance.onLaunch(message.payload);
        global.postMessage({
          type: 'APP_READY',
          payload: { entryPage: __GOAT_ENTRY_PAGE__, appId: __GOAT_APP_ID__ }
        });
        break;

      case 'UI_EVENT':
        // Handle DOM event forwarding from WebView
        if (message.handler && typeof global[message.handler] === 'function') {
          global[message.handler](message.event);
        }
        break;

      default:
        break;
    }
  };

  global.__GOAT_WORKER_READY__ = true;
})(typeof globalThis !== 'undefined' ? globalThis : self);
`;
}

function generateWebviewHtml(input: BundlerInput): string {
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0, maximum-scale=1.0, user-scalable=no, viewport-fit=cover">
  <title>${input.manifest.appName}</title>
  <link rel="stylesheet" href="appview.css">
</head>
<body>
  <div id="app" class="goat-page-container"></div>
  <script src="appview.renderer.js"></script>
</body>
</html>`;
}

function generateRendererScript(input: BundlerInput): string {
  return `/**
 * Goat WebView Mini-App View Thread (DOM Renderer)
 * Auto-generated by @goat/compiler-uniapp
 */
(function(window) {
  'use strict';

  const rootElement = document.getElementById('app');
  let currentRoute = ${JSON.stringify(input.manifest.entryPage)};

  function renderPage(route) {
    if (!rootElement) return;
    rootElement.innerHTML = '<div class="goat-page" data-route="' + route + '"></div>';
  }

  // Listen for worker messages
  window.addEventListener('message', function(event) {
    const msg = event.data;
    if (!msg || typeof msg !== 'object') return;

    if (msg.type === 'UI_PATCH') {
      // Apply VDOM mutations
    } else if (msg.type === 'NAVIGATE') {
      currentRoute = msg.route;
      renderPage(currentRoute);
    }
  });

  // Initial render
  renderPage(currentRoute);
})(typeof window !== 'undefined' ? window : this);
`;
}
