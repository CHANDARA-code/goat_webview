/**
 * @goat/compiler-uniapp Single-Thread SPA Bundler
 * Compiles Uni-app project into unified SPA web distribution bundle.
 */
import { generateIntegrityManifest } from './integrity.js';
import { transformRpxInCss } from '../runtime/rpx.js';
import type {
  BundleFileArtifact,
  BundlerInput,
  BundlerOutput,
} from '../types.js';

export function compileSingleThreadBundle(input: BundlerInput): BundlerOutput {
  const artifacts: BundleFileArtifact[] = [];

  // 1. Emit manifest.json
  const manifestJson = JSON.stringify(input.manifest, null, 2);
  artifacts.push({
    path: 'manifest.json',
    content: manifestJson,
  });

  // 2. Emit goat.config.json
  const goatConfigJson = JSON.stringify(input.goatConfig, null, 2);
  artifacts.push({
    path: 'goat.config.json',
    content: goatConfigJson,
  });

  // 3. Emit index.html (SPA entrypoint)
  const indexHtml = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0, maximum-scale=1.0, user-scalable=no, viewport-fit=cover">
  <title>${input.manifest.appName}</title>
  <link rel="stylesheet" href="assets/app.css">
</head>
<body>
  <div id="app"></div>
  <script src="assets/app.js"></script>
</body>
</html>`;
  artifacts.push({
    path: 'index.html',
    content: indexHtml,
  });

  // 4. Emit assets/app.js
  const appJs = `/**
 * Goat WebView Single-Thread Mini-App SPA Bundle
 * AppID: ${input.manifest.appId} | Version: ${input.manifest.version}
 * Auto-generated by @goat/compiler-uniapp
 */
(function(window) {
  'use strict';

  const entryPage = ${JSON.stringify(input.manifest.entryPage)};
  const routes = ${JSON.stringify(input.goatConfig.pages)};

  console.log('[GoatSPA] Mini-App Initialized:', entryPage);

  document.addEventListener('DOMContentLoaded', function() {
    const root = document.getElementById('app');
    if (root) {
      root.innerHTML = '<div class="goat-page" data-route="' + entryPage + '"></div>';
    }
  });
})(typeof window !== 'undefined' ? window : this);
`;
  artifacts.push({
    path: 'assets/app.js',
    content: appJs,
  });

  // 5. Emit assets/app.css
  const appCss = `
html, body {
  margin: 0;
  padding: 0;
  width: 100%;
  height: 100%;
  background-color: ${input.manifest.window?.backgroundColor || '#FFFFFF'};
  font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;
}
`;
  artifacts.push({
    path: 'assets/app.css',
    content: transformRpxInCss(appCss),
  });

  // 6. Generate SHA-256 integrity manifest
  const integrity = generateIntegrityManifest(artifacts);
  artifacts.push({
    path: 'integrity.json',
    content: JSON.stringify(integrity, null, 2),
  });

  return {
    artifacts,
    integrity,
    entryPage: input.manifest.entryPage,
    threadModel: 'single-thread',
  };
}
